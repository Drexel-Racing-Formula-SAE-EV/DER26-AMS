static float lut2d(float u0, float u1,
                   const float *bp0, uint32_t n0,
                   const float *bp1, uint32_t n1,
                   const float *table)
{
    uint32_t i0 = 0U;
    float f0 = 0.0f;

    if (u0 <= bp0[0])
    {
        i0 = 0U;
        f0 = 0.0f;
    }
    else if (u0 >= bp0[n0 - 1U])
    {
        i0 = n0 - 2U;
        f0 = 1.0f;
    }
    else
    {
        for (i0 = 0U; i0 < (n0 - 2U); i0++)
        {
            if (u0 < bp0[i0 + 1U])
            {
                break;
            }
        }
        f0 = (u0 - bp0[i0]) / (bp0[i0 + 1U] - bp0[i0]);
    }

    uint32_t i1 = 0U;
    float f1 = 0.0f;

    if (u1 <= bp1[0])
    {
        i1 = 0U;
        f1 = 0.0f;
    }
    else if (u1 >= bp1[n1 - 1U])
    {
        i1 = n1 - 2U;
        f1 = 1.0f;
    }
    else
    {
        for (i1 = 0U; i1 < (n1 - 2U); i1++)
        {
            if (u1 < bp1[i1 + 1U])
            {
                break;
            }
        }
        f1 = (u1 - bp1[i1]) / (bp1[i1 + 1U] - bp1[i1]);
    }

    float v00 = table[i0      + (i1 * n0)];
    float v10 = table[i0 + 1U + (i1 * n0)];
    float v01 = table[i0      + ((i1 + 1U) * n0)];
    float v11 = table[i0 + 1U + ((i1 + 1U) * n0)];

    return ((v00 + ((v10 - v00) * f0)) * (1.0f - f1)) +
           ((v01 + ((v11 - v01) * f0)) * f1);
}

float ams_p42a_ocv_v(float soc, float temp_c)
{
    return lut2d(soc, temp_c, s_SoC_bp_101, 101U, s_T_bp, 3U, s_OCV_table);
}

float ams_p42a_r0_ohm(float soc, float temp_c)
{
    return lut2d(soc, temp_c, s_SoC_bp_12, 12U, s_T_bp, 3U, s_R0_table);
}

float ams_p42a_inv_c1(float soc, float temp_c)
{
    return lut2d(soc, temp_c, s_SoC_bp_12, 12U, s_T_bp, 3U, s_C1_table);
}

float ams_p42a_neg_inv_tau1(float soc, float temp_c)
{
    return lut2d(soc, temp_c, s_SoC_bp_12, 12U, s_T_bp, 3U, s_R1C1_table);
}

float ams_p42a_inv_r1_from_luts(float inv_c1, float neg_inv_tau1)
{
    float inv_c1_safe = inv_c1;

    if (inv_c1_safe < 1.0e-6f)
    {
        inv_c1_safe = 1.0e-6f;
    }

    float inv_r1 = (-neg_inv_tau1) / inv_c1_safe;

    if (inv_r1 < 0.0f)
    {
        inv_r1 = 0.0f;
    }
    else if (inv_r1 > 1000.0f)
    {
        inv_r1 = 1000.0f;
    }

    return inv_r1;
}
