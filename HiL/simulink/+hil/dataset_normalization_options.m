function options = dataset_normalization_options(dataset_cfg, varargin)
%DATASET_NORMALIZATION_OPTIONS Convert declared source units to SI scales.

parser = inputParser();
parser.addParameter('AllowMissingCurrent', false, ...
    @(x) islogical(x) && isscalar(x));
parser.parse(varargin{:});

required = {'time', 'current', 'voltage', 'temperature', 'capacity'};
for index = 1:numel(required)
    if ~isfield(dataset_cfg.units, required{index})
        error('hil:data:UnitDeclaration', ...
            'Dataset units are missing "%s".', required{index});
    end
end

options = struct( ...
    'current_sign', dataset_cfg.current_sign, ...
    'time_scale_to_s', unit_scale( ...
        dataset_cfg.units.time, {'s', 'sec', 'second', 'seconds'}, ...
        {'ms', 'millisecond', 'milliseconds'}, 1e-3), ...
    'current_scale_to_A', unit_scale( ...
        dataset_cfg.units.current, {'a', 'amp', 'amps', 'ampere', 'amperes'}, ...
        {'ma', 'milliamp', 'milliamps', 'milliampere', 'milliamperes'}, 1e-3), ...
    'voltage_scale_to_V', unit_scale( ...
        dataset_cfg.units.voltage, {'v', 'volt', 'volts'}, ...
        {'mv', 'millivolt', 'millivolts'}, 1e-3), ...
    'temperature_scale_to_C', temperature_scale( ...
        dataset_cfg.units.temperature), ...
    'capacity_scale_to_Ah', unit_scale( ...
        dataset_cfg.units.capacity, {'ah', 'amphour', 'amphours'}, ...
        {'mah', 'milliamphour', 'milliamphours'}, 1e-3), ...
    'allow_missing_current', parser.Results.AllowMissingCurrent, ...
    'surface_temperature_source', optional_text( ...
        dataset_cfg, 'surface_temperature_source'), ...
    'source_units', dataset_cfg.units);
end

function value = optional_text(cfg, field_name)
if isfield(cfg, field_name)
    value = char(string(cfg.(field_name)));
else
    value = '';
end
end

function scale = unit_scale(value, base_units, milli_units, milli_scale)
unit = normalized_unit(value);
if ismember(unit, base_units)
    scale = 1.0;
elseif ismember(unit, milli_units)
    scale = milli_scale;
else
    error('hil:data:UnsupportedUnit', ...
        'Unsupported declared dataset unit "%s".', char(string(value)));
end
end

function scale = temperature_scale(value)
unit = normalized_unit(value);
if ~ismember(unit, {'c', 'degc', 'celsius', 'degreecelsius'})
    error('hil:data:UnsupportedTemperatureUnit', ...
        ['Temperature data must be declared in degC. Offset-bearing units ' ...
         'such as kelvin require conversion in a dataset-specific adapter.']);
end
scale = 1.0;
end

function unit = normalized_unit(value)
unit = lower(regexprep(char(string(value)), '[^a-zA-Z]', ''));
end
