clear; clc;

%% ============================================================
%  Add AMS-style vector outputs to frozen P42A 75s6p plant
%  Fully automated, no manual Simulink wiring.
%
%  Creates:
%       drev_75s6p_p42a_accumulator_plant_v3_ams_outputs.slx
%
%  Adds:
%       V_group[75]
%       V_segment[5]
%       T_sensor[120]
%       SoC_group[75]
%       V_min
%       V_max
%       T_max
%       T_avg
%
%  This version avoids workspace vector parameters inside the MATLAB
%  Function block. Offsets are deterministic formulas, codegen-safe.
%% ============================================================

%% Base/new model
base_candidates = { ...
    'drev_75s6p_p42a_accumulator_plant_v2_batch_validated', ...
    'drev_75s6p_p42a_accumulator_plant_v2_validated', ...
    'drev_75s6p_p42a_accumulator_plant_v1_r0_r1c1'};

base_mdl = '';

for k = 1:numel(base_candidates)
    if exist([base_candidates{k} '.slx'], 'file') == 4 || bdIsLoaded(base_candidates{k})
        base_mdl = base_candidates{k};
        break;
    end
end

if isempty(base_mdl)
    error('Could not find a valid base model .slx file.');
end

new_mdl = 'drev_75s6p_p42a_accumulator_plant_v3_ams_outputs';

fprintf('Base model: %s\n', base_mdl);
fprintf('New model:  %s\n', new_mdl);

%% Parameter file
param_file = fullfile(getenv('USERPROFILE'), ...
    'Documents', 'BMS_P42A_Data', 'mat_params', ...
    'params_p42a_75s6p_final_batch_validated.mat');

if exist(param_file, 'file') ~= 2
    param_file = fullfile(getenv('USERPROFILE'), ...
        'Documents', 'BMS_P42A_Data', 'mat_params', ...
        'params_p42a_75s6p_r0_r1c1_r2c2_real_v2.mat');
end

if exist(param_file, 'file') ~= 2
    error('Could not find parameter MAT file.');
end

fprintf('Parameter file:\n%s\n', param_file);

S = load(param_file);
fn = fieldnames(S);
for k = 1:numel(fn)
    assignin('base', fn{k}, S.(fn{k}));
end

%% Recreate new model from clean base
if bdIsLoaded(new_mdl)
    close_system(new_mdl, 0);
end

if exist([new_mdl '.slx'], 'file') == 4
    delete([new_mdl '.slx']);
end

load_system(base_mdl);
save_system(base_mdl, [new_mdl '.slx']);
load_system(new_mdl);

mdl = new_mdl;

%% Remove failed previous block/output attempts if any
delete_if_exists([mdl '/Accumulator_Output_Expansion']);

new_outs = {'V_group','V_segment','T_sensor','SoC_group','V_min','V_max','T_max','T_avg'};

for k = 1:numel(new_outs)
    delete_if_exists([mdl '/' new_outs{k}]);
    delete_if_exists([mdl '/' new_outs{k} '_spec']);
end

%% Add MATLAB Function block
blk = [mdl '/Accumulator_Output_Expansion'];

add_block('simulink/User-Defined Functions/MATLAB Function', blk, ...
    'Position', [660 220 940 410]);

rt = sfroot;
machine = rt.find('-isa', 'Stateflow.Machine', 'Name', mdl);
chart = machine.find('-isa', 'Stateflow.EMChart', 'Name', 'Accumulator_Output_Expansion');

if isempty(chart)
    error('Could not find MATLAB Function chart.');
end

chart.Script = strjoin({ ...
'function [V_group, V_segment, T_sensor, SoC_group, V_min, V_max, T_max, T_avg] = Accumulator_Output_Expansion(V_pack, T_core, T_surf, SoC_true)', ...
'%#codegen', ...
'', ...
'V_group = zeros(75,1,''single'');', ...
'V_segment = zeros(5,1,''single'');', ...
'T_sensor = zeros(120,1,''single'');', ...
'SoC_group = zeros(75,1,''single'');', ...
'', ...
'V_pack_s = single(V_pack);', ...
'T_core_s = single(T_core);', ...
'T_surf_s = single(T_surf);', ...
'SoC_s = single(SoC_true);', ...
'', ...
'V_cell_nom = V_pack_s / single(75.0);', ...
'', ...
'% Synthetic deterministic voltage spread, roughly +/-4 mV.', ...
'% Then corrected so sum(V_group) exactly equals V_pack.', ...
'sum_v = single(0.0);', ...
'for i = 1:75', ...
'    raw = single(mod(i * 37, 75)) / single(74.0);', ...
'    off = single(0.008) * (raw - single(0.5));', ...
'    V_group(i) = V_cell_nom + off;', ...
'    sum_v = sum_v + V_group(i);', ...
'end', ...
'', ...
'corr = (V_pack_s - sum_v) / single(75.0);', ...
'for i = 1:75', ...
'    V_group(i) = V_group(i) + corr;', ...
'end', ...
'', ...
'% 5 segment voltages, 15 series groups each.', ...
'for seg = 1:5', ...
'    acc = single(0.0);', ...
'    base = (seg - 1) * 15;', ...
'    for j = 1:15', ...
'        acc = acc + V_group(base + j);', ...
'    end', ...
'    V_segment(seg) = acc;', ...
'end', ...
'', ...
'% Synthetic group SoC spread, roughly +/-0.5%.', ...
'for i = 1:75', ...
'    raw = single(mod(i * 29, 75)) / single(74.0);', ...
'    off = single(0.010) * (raw - single(0.5));', ...
'    s = SoC_s + off;', ...
'    if s > single(1.0)', ...
'        s = single(1.0);', ...
'    elseif s < single(0.0)', ...
'        s = single(0.0);', ...
'    end', ...
'    SoC_group(i) = s;', ...
'end', ...
'', ...
'% 120 thermistors = 5 segments x 24 sensors.', ...
'% Mostly surface-like, every 6th sensor biased toward core.', ...
'for i = 1:120', ...
'    raw = single(mod(i * 17, 41)) - single(20.0);', ...
'    temp_off = raw / single(20.0);', ...
'    if mod(i,6) == 0', ...
'        T_sensor(i) = single(0.65)*T_core_s + single(0.35)*T_surf_s + temp_off;', ...
'    else', ...
'        T_sensor(i) = T_surf_s + temp_off;', ...
'    end', ...
'end', ...
'', ...
'% Voltage min/max.', ...
'V_min = V_group(1);', ...
'V_max = V_group(1);', ...
'for i = 2:75', ...
'    if V_group(i) < V_min', ...
'        V_min = V_group(i);', ...
'    end', ...
'    if V_group(i) > V_max', ...
'        V_max = V_group(i);', ...
'    end', ...
'end', ...
'', ...
'% Temperature max/average.', ...
'T_max = T_sensor(1);', ...
'sum_t = single(0.0);', ...
'for i = 1:120', ...
'    if T_sensor(i) > T_max', ...
'        T_max = T_sensor(i);', ...
'    end', ...
'    sum_t = sum_t + T_sensor(i);', ...
'end', ...
'T_avg = sum_t / single(120.0);' ...
}, newline);

%% Update to create MATLAB Function ports
set_param(mdl, 'SimulationCommand', 'update');

%% Connect existing scalar signals into function block inputs
ph = get_param(blk, 'PortHandles');

connect_from_existing_outport_signal(mdl, 'V_pack',   ph.Inport(1));
connect_from_existing_outport_signal(mdl, 'T_core',   ph.Inport(2));
connect_from_existing_outport_signal(mdl, 'T_surf',   ph.Inport(3));
connect_from_existing_outport_signal(mdl, 'SoC_true', ph.Inport(4));

%% Update again after input connections
set_param(mdl, 'SimulationCommand', 'update');
ph = get_param(blk, 'PortHandles');

%% Add Signal Specification + root Outport blocks
dims = {'[75 1]','[5 1]','[120 1]','[75 1]','[1 1]','[1 1]','[1 1]','[1 1]'};

x_spec = 1040;
x_out  = 1200;
y0 = 210;
dy = 46;

for k = 1:numel(new_outs)
    spec_blk = [mdl '/' new_outs{k} '_spec'];
    out_blk  = [mdl '/' new_outs{k}];

    add_block('simulink/Signal Attributes/Signal Specification', spec_blk, ...
        'Position', [x_spec y0+(k-1)*dy x_spec+80 y0+22+(k-1)*dy]);

    set_param(spec_blk, ...
        'Dimensions', dims{k}, ...
        'OutDataTypeStr', 'single');

    add_block('simulink/Sinks/Out1', out_blk, ...
        'Position', [x_out y0+(k-1)*dy x_out+80 y0+22+(k-1)*dy]);

    spec_ph = get_param(spec_blk, 'PortHandles');
    out_ph  = get_param(out_blk, 'PortHandles');

    add_line(mdl, ph.Outport(k), spec_ph.Inport(1), 'autorouting', 'on');
    add_line(mdl, spec_ph.Outport(1), out_ph.Inport(1), 'autorouting', 'on');
end

%% Re-apply critical settings
if block_exists([mdl '/I_pack_to_cell'])
    set_param([mdl '/I_pack_to_cell'], 'Gain', '1/6');
end

if block_exists([mdl '/V_cell_to_pack'])
    set_param([mdl '/V_cell_to_pack'], 'Gain', '75');
end

if block_exists([mdl '/dSoC_per_step'])
    set_param([mdl '/dSoC_per_step'], 'Gain', '-1/(3600*Q_nom)');
end

if block_exists([mdl '/SoC_Integrator'])
    set_param([mdl '/SoC_Integrator'], 'SampleTime', '0.1');
end

if block_exists([mdl '/ T_clamp'])
    set_param([mdl '/ T_clamp'], 'LowerLimit', '5', 'UpperLimit', '40');
end

%% Final update/save
set_param(mdl, 'SimulationCommand', 'update');
save_system(mdl);

fprintf('\nCreated and saved:\n%s.slx\n', mdl);

fprintf('\nAdded AMS outputs:\n');
disp(new_outs.');

fprintf('\nNext: run sanity test on vector outputs.\n');

%% ============================================================
% Helpers
%% ============================================================

function tf = block_exists(path)
    try
        get_param(path, 'Handle');
        tf = true;
    catch
        tf = false;
    end
end

function delete_if_exists(path)
    if block_exists(path)
        try
            delete_block(path);
        catch
            warning('Could not delete block: %s', path);
        end
    end
end

function connect_from_existing_outport_signal(mdl, outport_name, dst_port_handle)
    out_blk = find_system(mdl, ...
        'SearchDepth', 1, ...
        'BlockType', 'Outport', ...
        'Name', outport_name);

    if isempty(out_blk)
        error('Could not find root Outport named "%s".', outport_name);
    end

    lh = get_param(out_blk{1}, 'LineHandles');

    if lh.Inport == -1
        error('Outport "%s" has no incoming signal.', outport_name);
    end

    src_port = get_param(lh.Inport, 'SrcPortHandle');

    add_line(mdl, src_port, dst_port_handle, 'autorouting', 'on');
end